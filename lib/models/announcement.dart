class Announcement {
  final String id;
  final String societyId;
  final String title;
  final String content;
  final DateTime date;
  final String authorId;

  Announcement({
    required this.id,
    required this.societyId,
    required this.title,
    required this.content,
    required this.date,
    required this.authorId,
  });
}
